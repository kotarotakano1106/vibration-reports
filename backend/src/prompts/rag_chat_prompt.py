def build_rag_chat_input(
    *,
    query: str,
    context: str,
) -> str:
    """利用者の質問と検索コンテキストを回答生成用に整形する。"""

    return (
        "以下の過去レポート情報を根拠に質問へ回答してください。\n\n"
        f"【質問】\n{query}\n\n"
        f"【過去レポート情報】\n{context}"
    )
